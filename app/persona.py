def _pick_city(used_cities: list[str] | None = None) -> str:
    """輪流挑主要城市（確保前幾個水軍分佈全島），再用過就抽次要城市"""
    used = used_cities or []
    remaining = [c for c in TW_CITIES_MAJOR if c not in used]
    if remaining:
        return remaining[0]
    return random.choice(TW_CITIES_OTHER)


